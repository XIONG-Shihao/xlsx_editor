/** The standalone editor's API on host-owned invocation and event ports. */
export function createStandaloneApi({ invoke: invokeHost, subscribe }) {
  const invoke = (name, ...args) => invokeHost('xlsx:' + name, ...args);
  return {
    current: () => invoke('current'),
    open: () => invoke('open'),
    activateOpen: (id, discardPrevious) => invoke('activate-open', id, discardPrevious),
    cancelOpen: (id) => invoke('cancel-open', id),
    documents: () => invoke('documents'),
    activateTab: (id) => invoke('activate-tab', id),
    closeTab: (id) => invoke('close-tab', id),
    closeAll: () => invoke('close-all'),
    onDocuments: (callback) => subscribe('xlsx:documents', callback),
    calculation: (id, request) => invoke('calculation', id, request),
    cancelCalculation: (id, documentId, requestId) => invoke('cancel-calculation', id, documentId, requestId),
    onCalculationProgress: (callback) => subscribe('xlsx:calculation-progress', callback),
    importFile: (id, request) => invoke('import-delimited', id, request),
    cancelPaste: (id, documentId, requestId) => invoke('cancel-paste', id, documentId, requestId),
    dataOnlyExport: (id, request) => invoke('data-only-export', id, request),
    queryConnection: (id, request) => invoke('query-connection', id, request),
    refreshAllQueries: (id, request) => invoke('query-refresh-all', id, request),
    cancelQuery: (id, documentId, requestId) => invoke('cancel-query', id, documentId, requestId),
    spelling: (id, request) => invoke('spelling', id, request),
    localActions: (id, request) => invoke('local-actions', id, request),
    recentFiles: () => invoke('recent-files'),
    openRecent: (id) => invoke('open-recent', id),
    removeRecent: (id) => invoke('remove-recent', id),
    newWorkbook: () => invoke('new'),
    save: (id) => invoke('save', id),
    recoveryFiles: () => invoke('recovery-files'),
    openRecovery: (id) => invoke('open-recovery', id),
    operation: () => invoke('operation'),
    cancelOperation: (id, documentId) => invoke('cancel-operation', id, documentId),
    reload: (id) => invoke('reload', id),
    reopenRecovery: (id) => invoke('reopen-recovery', id),
    copyRecovery: (id) => invoke('copy-recovery', id),
    discardRecovery: (id) => invoke('discard-recovery', id),
    request: (id, request) => invoke('request', id, request),
    copy: (id) => invoke('copy', id),
    confirmLeave: (id, allowKeepRecovery = false) => invoke('confirm-leave', id, allowKeepRecovery),
    publishPrint: (id, request) => invoke('publish-print', id, request),
    cancelPrint: (id, documentId, requestId) => invoke('cancel-print', id, documentId, requestId),
    followHyperlink: (id, request) => invoke('follow-hyperlink', id, request),
    copyText: (text) => invoke('clipboard-write', text),
    readClipboardText: () => invoke('clipboard-read'),
    closeResult: (accepted) => invoke('close-result', accepted),
    onClose: (callback) => subscribe('xlsx:close-request', callback),
    onAction: (callback) => subscribe('xlsx:action', callback),
    onProgress: (callback) => subscribe('xlsx:progress', callback),
  };
}
